// NAMING CONVENTIONS IN JAVASCRIPT

// 1 . camelCase: The first word is in lowercase, and the first letter of each subsequent word is capitalized. Example: myVariableName

// use camelCase for variable names and function names in JavaScript. It is the most common naming convention used in JavaScript.

var myVariableName = "hello india "
console.log(myVariableName); // Output: hello india 

// 2. PascalCase: The first letter of each word is capitalized. Example: MyVariableName 

// use PascalCase for class names and constructors in JavaScript. It is also known as UpperCamelCase.

var MyVariableName = "hello SPAIN "; // valid, can start with a letter
console.log(myVariableName); // Output: hello india 

// 3. snake_case: All letters are lowercase, and words are separated by underscores. Example: my_variable_name

// used for variable names in JavaScript, but it is not as common as camelCase.

var my_variable_name = "hello germany ";
console.log(my_variable_name); // Output: hello india

// 4. screaming snake case: All letters are uppercase, and words are separated by underscores. Example: MY_VARIABLE_NAME
// mostly used for constants

var MY_VARIABLE_NAME = "hello france ";
console.log(MY_VARIABLE_NAME); // Output: hello india   