// THREE WAYS TO DECLARE VARIABLES IN JAVASCRIPT

// 1. var
var nm = "John";
console.log(nm); // Output: John

// 2. let
let age = 30;
console.log(age); // Output: 30

// 3. const
const height = 5.9;
console.log(height); // Output: 5.9

