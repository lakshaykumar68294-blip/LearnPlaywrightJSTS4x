// TERNARY OPERATOR
// SYNTAX--- condition? value 1: value 2;
// If condition is true value 1 is printed , else(if false) value 2 is printed

let age = 23;
let can_go_to_goa = age > 18? "yes can go" : " no cannot go";
console.log(can_go_to_goa);

let eligiblity = age > 18 ? " can vote" : " no cannot vote";
console.log(eligiblity);

